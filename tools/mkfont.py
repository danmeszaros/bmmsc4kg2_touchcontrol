#!/usr/bin/env python3
"""Generate 4-bit antialiased bitmap fonts for the firmware from TTF files.

    python3 tools/mkfont.py            # writes src/gfx/fonts_gen.{h,cc}

Edit FONTS to add sizes. Output is committed, so the firmware build does not
need Python or the TTF files.
"""
import os
from PIL import Image, ImageDraw, ImageFont

TTF_DIR = "/usr/share/fonts/truetype/dejavu/"
REGULAR = TTF_DIR + "DejaVuSans.ttf"
BOLD = TTF_DIR + "DejaVuSans-Bold.ttf"

# name, ttf, pixel size (same sizes as the mockups in docs/mockups),
# characters (None = all of CHARS)
FONTS = [
    ("font_10", REGULAR, 10, None),
    ("font_11b", BOLD, 11, None),
    ("font_12", REGULAR, 12, None),
    ("font_12b", BOLD, 12, None),
    ("font_13b", BOLD, 13, None),
    ("font_14", REGULAR, 14, None),
    ("font_15b", BOLD, 15, None),
    ("font_16b", BOLD, 16, None),
    ("font_20b", BOLD, 20, None),
    ("font_22b", BOLD, 22, None),
    ("font_34", REGULAR, 34, "+-−"),
    ("font_38b", BOLD, 38, None),
    ("font_52b", BOLD, 52, "f/0123456789.-K "),
]

CHARS = sorted([chr(c) for c in range(32, 127)] + ["°", "·", "−", "▾", "↔"])  # sorted: binary search

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "src/gfx/fonts_gen.h")
OUT_CC = os.path.join(ROOT, "src/gfx/fonts_gen.cc")


def render_font(name, ttf, size, chars=None):
    f = ImageFont.truetype(ttf, size)
    ascent, descent = f.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in (sorted(set(chars) | {"?"}) if chars else CHARS):
        adv = round(f.getlength(ch))
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")  # relative to the baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bits)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            px = im.load()
            for y in range(h):
                row = [(px[x, y] + 8) // 17 for x in range(w)]  # 0..255 -> 0..15
                if len(row) % 2:
                    row.append(0)
                for i in range(0, len(row), 2):
                    bits.append((row[i] << 4) | row[i + 1])
        else:
            w = h = 0
        glyphs.append((ord(ch), off, w, h, x0, y0, adv))
    return dict(name=name, ascent=ascent, descent=descent, glyphs=glyphs, bits=bits, src=os.path.basename(ttf), size=size)


def main():
    fonts = [render_font(*f) for f in FONTS]
    with open(OUT_H, "w") as h:
        h.write("// generated by tools/mkfont.py, do not edit\n#pragma once\n\n#include \"font.h\"\n\n")
        for f in fonts:
            h.write(f"extern const Font {f['name']}; // {f['src']} {f['size']} px\n")
    with open(OUT_CC, "w") as c:
        c.write("// generated by tools/mkfont.py, do not edit\n// DejaVu fonts: see https://dejavu-fonts.github.io/License.html\n")
        c.write("#include \"fonts_gen.h\"\n\n")
        for f in fonts:
            n = f["name"]
            c.write(f"static const uint8_t {n}_bits[{max(1, len(f['bits']))}] = {{\n")
            b = f["bits"] or bytearray([0])
            for i in range(0, len(b), 24):
                c.write("    " + ",".join(f"0x{v:02x}" for v in b[i:i + 24]) + ",\n")
            c.write("};\n")
            c.write(f"static const Glyph {n}_glyphs[{len(f['glyphs'])}] = {{\n")
            for cp, off, w, hh, x0, y0, adv in f["glyphs"]:
                c.write(f"    {{0x{cp:04x}, {off}, {w}, {hh}, {x0}, {y0}, {adv}}},\n")
            c.write("};\n")
            c.write(f"const Font {n} = {{{f['ascent']}, {f['descent']}, {len(f['glyphs'])}, {n}_glyphs, {n}_bits}};\n\n")
    total = sum(len(f["bits"]) for f in fonts)
    print(f"{len(fonts)} fonts, {total} bytes of bitmaps -> {OUT_CC}")


if __name__ == "__main__":
    main()
